#!/usr/bin/env node
// Keybinding drift tripwire.
//
// haus generates its live cheatsheet from modules/prowl/wm-bindings.nix, so a
// binding and its caption cannot disagree inside an install. The site's
// keybinding pages are prose, though. This script snapshots haus's binding
// surface and fails when it moves past what those pages were checked against.
//
// Usage:
//   node scripts/check-rice-bindings.mjs --haus <haus-checkout>
//   node scripts/check-rice-bindings.mjs --haus <haus-checkout> --update

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SNAPSHOT = join(here, '../src/data/rice-bindings.json');

const args = process.argv.slice(2);
const update = args.includes('--update');
const hausIdx = args.indexOf('--haus');
const haus = hausIdx >= 0 ? args[hausIdx + 1] : process.env.HAUS_DIR;
if (!haus || !existsSync(haus)) {
  console.error('usage: check-rice-bindings.mjs --haus <haus-checkout> [--update]');
  process.exit(2);
}

// The static chord table, resolved for haus's default keymap. haus publishes
// it as committed site data so this repository never evaluates Nix.
const WM_BINDINGS = join(haus, 'docs/site-data/wm-bindings.json');
if (!existsSync(WM_BINDINGS)) {
  console.error(
    [
      `The haus checkout at ${haus} has no \`docs/site-data/wm-bindings.json\`.`,
      '',
      'That file is generated and committed by haus (`nix build .#site-data`).',
      'Update the checkout and re-run.',
      '',
    ].join('\n'),
  );
  process.exit(1);
}
const wmBindings = JSON.parse(readFileSync(WM_BINDINGS, 'utf8'));

// The launch and resize mode keys live in aerospace.toml rather than in the
// published binding table. Snapshot keys only: commands contain substituted
// path noise that would churn this file without changing the docs.
function modeKeys(toml, mode) {
  const keys = [];
  let inSection = false;
  for (const line of toml.split('\n')) {
    if (line.startsWith('[')) {
      inSection = line.trim() === `[mode.${mode}.binding]`;
      continue;
    }
    if (!inSection) continue;
    const key = line.match(/^([\w-]+)\s*=/)?.[1];
    if (key) keys.push(key);
  }
  return keys;
}
const toml = readFileSync(join(haus, 'modules/prowl/aerospace.toml'), 'utf8');

const current =
  JSON.stringify(
    {
      _note: 'Generated by scripts/check-rice-bindings.mjs --update. Do not edit by hand.',
      wmBindings,
      launchModeKeys: modeKeys(toml, 'launch'),
      resizeModeKeys: modeKeys(toml, 'resize'),
    },
    null,
    2,
  ) + '\n';

if (update) {
  writeFileSync(SNAPSHOT, current);
  console.log(`snapshot refreshed: ${SNAPSHOT}`);
  process.exit(0);
}

let committed = '';
try {
  committed = readFileSync(SNAPSHOT, 'utf8');
} catch {
  console.error(`no snapshot at ${SNAPSHOT} — run with --update once to create it.`);
  process.exit(1);
}

if (committed === current) {
  console.log('haus bindings unchanged — docs are as current as the last human pass.');
  process.exit(0);
}

console.error("✗ haus's keybindings moved since the docs were last checked.\n");
const before = JSON.parse(committed);
const after = JSON.parse(current);
for (const key of ['wmBindings', 'launchModeKeys', 'resizeModeKeys']) {
  if (JSON.stringify(before[key]) !== JSON.stringify(after[key])) {
    console.error(`  changed: ${key}`);
    console.error(`    was: ${JSON.stringify(before[key])}`);
    console.error(`    now: ${JSON.stringify(after[key])}`);
  }
}
console.error(`
Update the pages that print these keys —
  content/docs/haus/desktops/hacker.mdx   (#first-moves)
  content/docs/haus/rooms/windows.mdx
  content/docs/haus/rooms/development.mdx
— then refresh the snapshot:
  node scripts/check-rice-bindings.mjs --haus <haus-checkout> --update`);
process.exit(1);
